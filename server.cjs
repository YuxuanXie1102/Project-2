app.post('/api/records', async (req,res) => {
 const {day,type,data}=req.body||{};
 if (!validDay(day)||!types.has(type)||!validData(data)) return res.status(400).json({error:'Invalid day, type or data'});
 const id=randomUUID(), now=new Date().toISOString();
 const row=await transaction(req.owner,async client=>{
  const result=await client.query('INSERT INTO records(id,owner,day,type,data,created_at,updated_at) VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *',[id,req.owner,day,type,JSON.stringify(data),now,now]);
  await advanceRevision(client,req.owner); return result.rows[0];
 });
 res.status(201).location('/api/records/'+id).json(output(row));
});
app.get('/api/records/:id',async(req,res)=>{
 const row=await find(db,req.params.id,req.owner);
 if (!row) return res.status(404).json({error:'Record not found'});
 res.json(output(row));
});
app.patch('/api/records/:id',async(req,res)=>{
 const body=req.body||{};
 if (Object.keys(body).some(k=>!['day','type','data'].includes(k))||!Object.keys(body).length||('day' in body&&!validDay(body.day))||('type' in body&&!types.has(body.type))||('data' in body&&!validData(body.data))) return res.status(400).json({error:'Invalid update'});
 const result=await transaction(req.owner,async client=>{
  const row=await find(client,req.params.id,req.owner);
  if (!row) return {status:404,error:'Record not found'};
  const data={...JSON.parse(row.data),...(body.data||{})};
  const {id: frontendId,...fields}=data;
  if (!validData(fields)) return {status:400,error:'Invalid merged data'};
  const updated=await client.query('UPDATE records SET day=$1,type=$2,data=$3,updated_at=$4 WHERE id=$5 AND owner=$6 RETURNING *',[body.day??row.day,body.type??row.type,JSON.stringify(data),new Date().toISOString(),row.id,req.owner]);
  await advanceRevision(client,req.owner); return {row:updated.rows[0]};
 });
 if (!result.row) return res.status(result.status).json({error:result.error});
 res.json(output(result.row));
});
app.delete('/api/records/:id',async(req,res)=>{
 const deleted=await transaction(req.owner,async client=>{
  const result=await client.query("DELETE FROM records WHERE id=$1 AND owner=$2 AND type IN ('todos','carry','checks')",[req.params.id,req.owner]);
  if (!result.rowCount) return false;
  await advanceRevision(client,req.owner); return true;
 });
 if (!deleted) return res.status(404).json({error:'Record not found'});
 res.status(204).end();
});
